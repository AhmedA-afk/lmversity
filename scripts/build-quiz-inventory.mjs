/**
 * Builds docs/registry/quiz-inventory.md — the lesson-quiz inventory and the
 * dedup audit between lesson-embedded quizzes and the centralized banks.
 *
 * Sources of truth:
 *   - Lesson quizzes: src/content/lessons/**\/*-quiz.{md,mdx} — questions are
 *     `## N. ...` sections; the prompt is the body up to the first `A.` option.
 *   - Centralized banks: src/data/quizzes.ts — q('prompt', ...) first arg.
 *
 * Dedup signal: normalized token-set Jaccard similarity between prompts.
 * Pairs >= 0.55 are flagged as candidates for editorial review; pairs >= 0.75
 * are flagged as likely duplicates. The report is the Milestone-B evidence.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const LESSONS = 'src/content/lessons';
const QUIZZES_TS = 'src/data/quizzes.ts';
const OUT = 'docs/registry/quiz-inventory.md';

const walk = (dir, acc = []) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/-quiz\.(md|mdx)$/.test(name)) acc.push(p);
  }
  return acc;
};

const norm = (s) =>
  new Set(
    s.toLowerCase()
      .replace(/<[^>]+>/g, ' ')
      .replace(/[^a-z0-9\s]/g, ' ')
      .split(/\s+/)
      .filter((w) => w.length > 2),
  );

const jaccard = (a, b) => {
  let inter = 0;
  for (const w of a) if (b.has(w)) inter++;
  return inter / (a.size + b.size - inter || 1);
};

// --- lesson quiz prompts ----------------------------------------------------
const lessonQuizzes = [];
for (const file of walk(LESSONS)) {
  const text = readFileSync(file, 'utf8');
  const body = text.replace(/^---[\s\S]*?---/, '');
  const rel = relative(LESSONS, file).replace(/\.(md|mdx)$/, '');
  // Question sections appear as `## N.`, `## Question N:`, `### N.`, or
  // bold-numbered `**N. prompt**` — split on any of them.
  const sections = body
    .split(/\n#{2,3} (?:Question |Q)?\d+[.:)]?\s+|\n\*\*Q?\d+[.:)]?\*{0,2}\s+/)
    .slice(1);
  const questions = sections.map((sec) => {
    const lines = sec.split('\n');
    const title = lines[0].replace(/\*\*$/, '').trim();
    const promptLines = [];
    for (const line of lines.slice(1)) {
      if (/^A\.\s/.test(line.trim()) || line.includes('<details>')) break;
      promptLines.push(line);
    }
    return { title, prompt: (title + ' ' + promptLines.join(' ')).trim() };
  });
  lessonQuizzes.push({ file: rel, track: rel.split('/')[0], questions });
}

// --- centralized bank prompts ------------------------------------------------
const qsrc = readFileSync(QUIZZES_TS, 'utf8');
// capture bank id context: track of the enclosing `id: 'x'` block
const bankQuestions = [];
const bankBlocks = qsrc.split(/\n\s*\{\s*\n?\s*id: '/).slice(1);
for (const block of bankBlocks) {
  const bankId = block.slice(0, block.indexOf("'"));
  const qRe = /\bq\(\s*'((?:[^'\\]|\\.)*)'/g;
  let m;
  while ((m = qRe.exec(block))) {
    bankQuestions.push({ bank: bankId, prompt: m[1].replace(/\\'/g, "'") });
  }
}

// --- dedup -------------------------------------------------------------------
const lessonAll = [];
for (const lq of lessonQuizzes)
  for (const q of lq.questions)
    lessonAll.push({ where: lq.file, title: q.title, prompt: q.prompt, toks: norm(q.prompt) });
const bankAll = bankQuestions.map((q) => ({ ...q, toks: norm(q.prompt) }));

const pairs = [];
for (const lq of lessonAll)
  for (const bq of bankAll)
    if (lq.where.split('/')[0] === bq.bank || true) {
      const sim = jaccard(lq.toks, bq.toks);
      if (sim >= 0.55) pairs.push({ sim, lesson: lq, bank: bq });
    }
// within-bank dupes
const bankPairs = [];
for (let i = 0; i < bankAll.length; i++)
  for (let j = i + 1; j < bankAll.length; j++) {
    const sim = jaccard(bankAll[i].toks, bankAll[j].toks);
    if (sim >= 0.55) bankPairs.push({ sim, a: bankAll[i], b: bankAll[j] });
  }
// within-lesson-quiz dupes
const lessonPairs = [];
for (let i = 0; i < lessonAll.length; i++)
  for (let j = i + 1; j < lessonAll.length; j++) {
    if (lessonAll[i].where === lessonAll[j].where) continue;
    const sim = jaccard(lessonAll[i].toks, lessonAll[j].toks);
    if (sim >= 0.55) lessonPairs.push({ sim, a: lessonAll[i], b: lessonAll[j] });
  }

pairs.sort((a, b) => b.sim - a.sim);
bankPairs.sort((a, b) => b.sim - a.sim);
lessonPairs.sort((a, b) => b.sim - a.sim);

const totalLessonQ = lessonAll.length;
const totalBankQ = bankAll.length;
const fmt = (s) => (s.length > 90 ? s.slice(0, 87) + '…' : s);

let md = `# Lesson-quiz inventory and dedup audit

Generated by \`scripts/build-quiz-inventory.mjs\` — ${new Date().toISOString().slice(0, 10)}.

Inventories the two question surfaces — lesson-embedded \`*-quiz\` pages and the
centralized banks in \`src/data/quizzes.ts\` — and audits overlap. Similarity is
token-set Jaccard on normalized prompts; ≥0.75 flags a likely duplicate, ≥0.55 a
review candidate. Same-topic questions with different prompts are intended
coverage, not duplication.

## Totals

| Surface | Files/banks | Questions |
|---|---|---|
| Lesson quizzes | ${lessonQuizzes.length} | ${totalLessonQ} |
| Centralized banks | ${new Set(bankAll.map((b) => b.bank)).size} | ${totalBankQ} |

## Lesson-quiz inventory

| Quiz file | Questions |
|---|---|
${lessonQuizzes.map((l) => `| \`${l.file}\` | ${l.questions.length} |`).join('\n')}

## Cross-surface candidates (lesson quiz × bank)

${pairs.length === 0 ? 'None at or above the 0.55 review threshold.' : pairs.map((p) => `- **${p.sim.toFixed(2)}** — \`${p.lesson.where}\` "${fmt(p.lesson.title)}" × bank \`${p.bank.bank}\` "${fmt(p.bank.prompt)}"`).join('\n')}

## Within-bank candidates

${bankPairs.length === 0 ? 'None at or above the 0.55 review threshold.' : bankPairs.map((p) => `- **${p.sim.toFixed(2)}** — \`${p.a.bank}\` "${fmt(p.a.prompt)}" × \`${p.b.bank}\` "${fmt(p.b.prompt)}"`).join('\n')}

## Within-lesson-quiz candidates (across files)

${lessonPairs.length === 0 ? 'None at or above the 0.55 review threshold.' : lessonPairs.map((p) => `- **${p.sim.toFixed(2)}** — \`${p.a.where}\` "${fmt(p.a.title)}" × \`${p.b.where}\` "${fmt(p.b.title)}"`).join('\n')}
`;

writeFileSync(OUT, md);
console.log(
  `quiz-inventory: ${lessonQuizzes.length} lesson quizzes / ${totalLessonQ} questions; ` +
    `${new Set(bankAll.map((b) => b.bank)).size} banks / ${totalBankQ} questions; ` +
    `cross ${pairs.length}, bank-internal ${bankPairs.length}, lesson-internal ${lessonPairs.length}`,
);
