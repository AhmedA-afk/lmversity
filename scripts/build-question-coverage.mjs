#!/usr/bin/env node
/**
 * Question-bank coverage matrix.
 *
 * Cross-references src/data/quizzes.ts (the bank) against src/data/curriculum.ts
 * (the canon). For every curriculum track: does a question bank exist, how many
 * live questions, which curriculum nodes they remediate to (the `module` field),
 * and how coverage distributes across difficulty, kind, and case.
 *
 * Output: docs/registry/question-coverage.md — read it as the production queue:
 * tracks with zero banks or zero module coverage are where the next batch goes.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const CURRICULUM = join(ROOT, 'src/data/curriculum.ts');
const QUIZZES = join(ROOT, 'src/data/quizzes.ts');
const OUT = join(ROOT, 'docs/registry/question-coverage.md');

// --- curriculum: track -> ordered live slugs (same parse as check-content) ---
const curSrc = readFileSync(CURRICULUM, 'utf8');
const trackMeta = new Map(); // id -> {name, liveSlugs[]}
const trackSpans = [...curSrc.matchAll(/^\s*"id":\s*"([\w-]+)",\s*$/gm)]
  .map((m, i, arr) => ({ id: m[1], from: m.index, to: arr[i + 1]?.index ?? curSrc.length }));
for (const { id, from, to } of trackSpans) {
  const seg = curSrc.slice(from, to);
  const name = seg.match(/"name":\s*"([^"]+)"/)?.[1] ?? id;
  const liveSlugs = [];
  for (const nb of seg.matchAll(/\{[^{}]*?"slug":\s*"([^"]+)"[^{}]*?\}/gs)) {
    const status = nb[0].match(/"status":\s*"(\w+)"/)?.[1] ?? 'live';
    if (status === 'live') liveSlugs.push(nb[1]);
  }
  trackMeta.set(id, { name, liveSlugs });
}

// --- bank: track -> questions with metadata ----------------------------------
const qsrc = readFileSync(QUIZZES, 'utf8');
const banks = new Map(); // id -> [{module, difficulty, kind, case, status, objective}]
const qTrackSpans = [...qsrc.matchAll(/id:\s*'([\w-]+)',\s*\n\s*name:\s*'([^']+)'/g)]
  .map((m, i, arr) => ({ id: m[1], name: m[2], from: m.index, to: arr[i + 1]?.index ?? qsrc.indexOf('];', m.index) }));
for (const { id, name, from, to } of qTrackSpans) {
  const seg = qsrc.slice(from, to);
  const questions = [];
  for (const line of seg.split('\n')) {
    if (!line.includes('q(')) continue;
    const meta = (k) => line.match(new RegExp(`${k}:\\s*'([^']+)'`))?.[1];
    questions.push({
      module: meta('module'), objective: meta('objective'),
      difficulty: meta('difficulty') ?? 'unspecified',
      kind: meta('kind') ?? 'unspecified',
      case: meta('case') ?? 'normal',
      status: meta('status') ?? 'live',
      retired: /status:\s*'retired'/.test(line),
    });
  }
  banks.set(id, { name, questions });
}

// Bank ids that legitimately differ from curriculum track ids (route stability —
// the bank id is the /practice/ URL, the curriculum id is the /learn/ one).
const BANK_TO_TRACK = { evals: 'evals-red-teaming' };
const bankFor = (id) => banks.get(id) ?? banks.get(Object.keys(BANK_TO_TRACK).find((b) => BANK_TO_TRACK[b] === id));

// --- matrix -------------------------------------------------------------------
const lines = [
  '# Question-bank coverage matrix',
  '',
  `Generated by \`scripts/build-question-coverage.mjs\` — ${new Date().toISOString().slice(0, 10)}.`,
  '',
  'The bank target is reviewed depth, not page count: 1,000 per major track is',
  'the long-horizon ceiling; narrow tracks carry smaller targets until their',
  'curriculum justifies more. Coverage % counts curriculum nodes a question',
  'explicitly remediates to (`module` field) — one question can cover one node.',
  '',
  '| Track | Bank | Live questions | Node coverage | Difficulty mix | Kind mix |',
  '|---|---|---|---|---|---|',
];

const dist = (qs, k) => {
  const c = {};
  for (const q of qs) c[q[k]] = (c[q[k]] ?? 0) + 1;
  return Object.entries(c).map(([v, n]) => `${v} ${n}`).join(', ') || '—';
};

let totalQ = 0, banked = 0;
for (const [id, { name, liveSlugs }] of trackMeta) {
  const bank = bankFor(id);
  const live = bank?.questions.filter((q) => !q.retired) ?? [];
  totalQ += live.length;
  const covered = new Set(live.map((q) => q.module).filter(Boolean));
  const pct = liveSlugs.length ? Math.round((covered.size / liveSlugs.length) * 100) : 0;
  if (bank) banked++;
  lines.push(`| ${name} (\`${id}\`) | ${bank ? '✓' : '—'} | ${live.length || '—'} | ${covered.size}/${liveSlugs.length} (${pct}%) | ${dist(live, 'difficulty')} | ${dist(live, 'kind')} |`);
}

// banks with no matching curriculum track (shouldn't happen — lint guards)
for (const [id, bank] of banks) {
  if (!trackMeta.has(id) && !BANK_TO_TRACK[id]) lines.push(`| ⚠ ${bank.name} (\`${id}\`) | ✓ | ${bank.questions.length} | no curriculum track | — | — |`);
}

lines.push(
  '',
  `**${totalQ} live questions across ${banked} banked tracks; ${trackMeta.size - banked} curriculum tracks have no bank yet.**`,
  '',
  '### Production queue (no bank)',
  '',
);
for (const [id, { name, liveSlugs }] of trackMeta) {
  if (!bankFor(id) && liveSlugs.length) lines.push(`- \`${id}\` — ${name} (${liveSlugs.length} live nodes)`);
}
lines.push(
  '',
  '### Deepest gaps (bank exists, <30% node coverage)',
  '',
);
for (const [id, { name, liveSlugs }] of trackMeta) {
  const bank = bankFor(id);
  if (!bank || !liveSlugs.length) continue;
  const covered = new Set(bank.questions.filter((q) => !q.retired).map((q) => q.module).filter(Boolean));
  if (covered.size / liveSlugs.length < 0.3) lines.push(`- \`${id}\` — ${covered.size}/${liveSlugs.length} nodes covered`);
}

mkdirSync(join(ROOT, 'docs/registry'), { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`question coverage: ${totalQ} questions, ${banked} banked tracks → ${relative(OUT)}`);

function relative(p) { return p.replace(ROOT, ''); }
